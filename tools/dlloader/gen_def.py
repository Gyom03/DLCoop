# Generates winmm_exports.h: the proxy winmm.dll (DLCoop's mod loader) forwards ALL functions of the real Windows
# winmm.dll, with the same ordinals. The forwards target its absolute path (\\.\GLOBALROOT\SystemRoot\System32\winmm),
# which avoids copying the system DLL next to the game; a .def file cannot express that, hence the
# "#pragma comment(linker, "/export:…")" directives.
# Input: the system winmm.dll (argument, default System32). Output: tools/dlloader/winmm_exports.h
import pefile, sys, os

src = sys.argv[1] if len(sys.argv) > 1 else r"C:\Windows\System32\winmm.dll"
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "winmm_exports.h")
real = r"\\\\.\\GLOBALROOT\\SystemRoot\\System32\\winmm"  # escaped for a C string

pe = pefile.PE(src, fast_load=True)
pe.parse_data_directories(directories=[pefile.DIRECTORY_ENTRY["IMAGE_DIRECTORY_ENTRY_EXPORT"]])
exp = pe.DIRECTORY_ENTRY_EXPORT

named = [(s.ordinal, s.name.decode()) for s in exp.symbols if s.name]
ordinal_only = [s.ordinal for s in exp.symbols if not s.name]

lines = ["// Generated by gen_def.py: proxy winmm -> system winmm.dll (System32), same ordinals.", "#pragma once"]
for o, n in named:
    lines.append('#pragma comment(linker, "/export:{0}={1}.{0},@{2}")'.format(n, real, o))
for o in ordinal_only:
    lines.append('#pragma comment(linker, "/export:winmm_ord{0}={1}.#{0},@{0},NONAME")'.format(o, real))
with open(out, "w", encoding="utf-8") as f:
    f.write("\n".join(lines) + "\n")

print("named exports forwarded:", len(named))
print("ordinal-only exports forwarded:", ordinal_only)
print("written:", out)
